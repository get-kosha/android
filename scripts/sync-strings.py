#!/usr/bin/env python3
"""Builds the app's strings.xml files from the web repo's message files, the one source for every string.

    python3 scripts/sync-strings.py [path to the kosha web repo, default ../kosha]

Reads messages/<locale>/<area>.json (inlang message format) for the areas the app shows and writes
core/design/src/main/res/values[-<locale>]/strings.xml. {name} variables become positional %1$s
arguments, {#tag}…{/tag} markup becomes <annotation tag="…">, and plural messages become <plurals>.
Add app-only strings to messages/<locale>/app.json in the web repo, in every locale, then run this again.
Lint's ImpliedQuantity and Typos checks are off for these files: the web repo owns the wording, and some
languages write their "one" form without the number, as the web shows it.
"""
import json
import re
import sys
from pathlib import Path

WEB = Path(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parents[1].parent / "kosha")
OUT = Path(__file__).resolve().parents[1] / "core/design/src/main/res"
# Landing, demos, legal and site are the web's marketing pages; server messages come back in API errors.
AREAS = ["common", "auth", "overview", "transactions", "add", "accounts", "reconcile", "import", "welcome",
         "settings", "settings-sections", "ai", "app"]
# Android's folder for each locale. pt is Brazilian Portuguese and zh Simplified Chinese (translations.md).
FOLDER = {"en": "values"}
PLURAL_KEYS = {"zero", "one", "two", "few", "many", "other"}


def escape(text: str, formatted: bool) -> str:
    text = text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    text = text.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if formatted:
        text = text.replace("%", "%%")
    if text.startswith(("@", "?")):
        text = "\\" + text
    return text


def convert(text: str, order: list[str]) -> str:
    """One message: variables to %n$s in the order first seen in English, markup to annotations."""
    names = re.findall(r"\{(\w+)\}", text)
    out = escape(text, formatted=bool(names))
    out = re.sub(r"\{(\w+)\}", lambda m: f"%{order.index(m.group(1)) + 1}$s" if m.group(1) in order else m.group(0), out)
    out = re.sub(r"\{#(\w+)\}", r'<annotation tag="\1">', out)
    out = re.sub(r"\{/(\w+)\}", "</annotation>", out)
    return out


def variables(value) -> list[str]:
    texts = [value] if isinstance(value, str) else list(value[0]["match"].values())
    seen: list[str] = []
    for t in texts:
        for n in re.findall(r"\{(\w+)\}", t):
            if n not in seen:
                seen.append(n)
    return seen


def plural(value) -> dict[str, str] | None:
    """A plural message's forms by Android quantity, or None for a selector Android can't express."""
    if len(value) != 1 or len(value[0].get("selectors", [])) != 1:
        return None
    forms = {}
    fallback = None
    for key, text in value[0]["match"].items():
        q = key.split("=", 1)[1]
        if q == "*":
            fallback = text
            continue
        if q not in PLURAL_KEYS:
            return None
        forms[q] = text
    # "*" matches every plural category the language has, so it fills each one not given explicitly.
    if fallback is not None:
        for q in PLURAL_KEYS:
            forms.setdefault(q, fallback)
    return forms if "other" in forms else None


def main():
    english = {}
    for area in AREAS:
        english.update(json.loads((WEB / f"messages/en/{area}.json").read_text()))
    english.pop("$schema", None)
    locales = sorted(p.name for p in (WEB / "messages").iterdir() if p.is_dir())
    skipped = set()
    for locale in locales:
        messages = {}
        for area in AREAS:
            messages.update(json.loads((WEB / f"messages/{locale}/{area}.json").read_text()))
        lines = ['<?xml version="1.0" encoding="utf-8"?>',
                 "<!-- Generated by scripts/sync-strings.py from the web repo's messages. Don't edit. -->",
                 '<resources xmlns:tools="http://schemas.android.com/tools" tools:ignore="UnusedResources,MissingTranslation,TypographyEllipsis,TypographyDashes,UnusedQuantity,ImpliedQuantity,Typos">']
        for key in english:
            value = messages.get(key)
            if value is None:
                continue
            order = variables(english[key])
            if isinstance(value, str):
                lines.append(f'    <string name="{key}">{convert(value, order)}</string>')
                continue
            forms = plural(value)
            if forms is None:
                skipped.add(key)
                continue
            lines.append(f'    <plurals name="{key}">')
            for q in ["zero", "one", "two", "few", "many", "other"]:
                if q in forms:
                    lines.append(f'        <item quantity="{q}">{convert(forms[q], order)}</item>')
            lines.append("    </plurals>")
        lines.append("</resources>")
        folder = OUT / FOLDER.get(locale, f"values-{locale}")
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "strings.xml").write_text("\n".join(lines) + "\n")
    print(f"{len(english)} messages, {len(locales)} locales", f"; skipped {sorted(skipped)}" if skipped else "")


main()
